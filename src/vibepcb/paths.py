"""Project layout: boards/<name>/index.circuit.tsx -> out/<name>/{raw,kicad}/."""

from __future__ import annotations

import os
from pathlib import Path


def find_root() -> Path:
    """The project root: ``$VIBEPCB_ROOT``, else the nearest parent of the cwd holding
    ``boards/`` and ``package.json`` (so the tool works from any project that depends on
    it), else this checkout."""
    if env := os.environ.get("VIBEPCB_ROOT"):
        return Path(env).resolve()
    cwd = Path.cwd().resolve()
    for candidate in (cwd, *cwd.parents):
        if (candidate / "boards").is_dir() and (candidate / "package.json").is_file():
            return candidate
    return Path(__file__).resolve().parents[2]


ROOT = find_root()
BOARDS_DIR = ROOT / "boards"
OUT_DIR = ROOT / "out"
DOCS_DIR = ROOT / "docs"


def board_source(name: str) -> Path:
    """The tscircuit entry file of board ``name``."""
    return BOARDS_DIR / name / "index.circuit.tsx"


def raw_dir(name: str) -> Path:
    """Untouched tscircuit exports (regenerated by every build)."""
    return OUT_DIR / name / "raw"


def kicad_dir(name: str) -> Path:
    """Post-processed KiCad project (open this one in KiCad)."""
    return OUT_DIR / name / "kicad"


def list_boards() -> list[str]:
    return sorted(p.parent.name for p in BOARDS_DIR.glob("*/index.circuit.tsx"))
