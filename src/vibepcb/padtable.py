"""Board positions of parts' pads from a placement build, as a TypeScript table the board source can use.

A pin plan (which FPGA ball carries which signal) is best made by geometry: pair a group of signals with
the FPGA's balls in the order they are seen from the partner part, so the routes do not cross. The
positions exist only once tscircuit has placed the board, so ``pcb padtable`` reads the placement-only
circuit JSON of the last build and writes ``boards/<board>/pads.ts``; the board source imports it and
the next build uses the plan (two passes, like any placement change).
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

HEADER = "// generated by `pcb padtable` from the placement build - do not edit; rerun after moving a part\n"


def pad_positions(
    circuit_json: Path, refs: list[str]
) -> tuple[dict[str, dict[str, tuple[float, float]]], dict[str, tuple[float, float]]]:
    """(ref -> port name -> (x, y)) and (ref -> part centre), in tscircuit board coordinates (mm, y up)."""
    elements = json.loads(circuit_json.read_text(encoding="utf-8"))
    names = {e["source_component_id"]: e["name"] for e in elements if e.get("type") == "source_component"}
    wanted = {cid for cid, name in names.items() if name in refs}
    ports = {
        e["source_port_id"]: (names[e["source_component_id"]], str(e["name"]))
        for e in elements
        if e.get("type") == "source_port" and e.get("source_component_id") in wanted
    }
    pads: dict[str, dict[str, tuple[float, float]]] = {ref: {} for ref in refs}
    for e in elements:
        if e.get("type") == "pcb_port" and e.get("source_port_id") in ports:
            ref, name = ports[e["source_port_id"]]
            pads[ref][name] = (round(float(e["x"]), 3), round(float(e["y"]), 3))
    centres = {
        names[e["source_component_id"]]: (round(float(e["center"]["x"]), 3), round(float(e["center"]["y"]), 3))
        for e in elements
        if e.get("type") == "pcb_component" and e.get("source_component_id") in wanted and "center" in e
    }
    missing = [ref for ref in refs if not pads[ref]]
    if missing:
        msg = f"no pads for {', '.join(missing)} in {circuit_json.name}"
        raise ValueError(msg)
    return pads, centres


def to_typescript(pads: dict[str, dict[str, tuple[float, float]]], centres: dict[str, tuple[float, float]]) -> str:
    lines = [HEADER, "export const PADS: Record<string, Record<string, readonly [number, number]>> = {"]
    for ref in sorted(pads):
        lines.append(f"  {ref}: {{")
        lines += [f"    {json.dumps(name)}: [{x}, {y}]," for name, (x, y) in sorted(pads[ref].items())]
        lines.append("  },")
    lines.append("}")
    lines.append("export const CENTRES: Record<string, readonly [number, number]> = {")
    lines += [f"  {ref}: [{x}, {y}]," for ref, (x, y) in sorted(centres.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"
